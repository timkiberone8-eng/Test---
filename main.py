from calculator_modules.arithmetic import add, subtract, multiply, divide


# БЫЛО так:
#
#     try:
#         def main():
#             ...
#     except ZeroDivisionError:
#         ...
#
# То есть ловушка была накинута на ОБЪЯВЛЕНИЕ функции. Объявление
# просто создаёт имя main и ничего не вычисляет: ни ValueError, ни
# ZeroDivisionError оно выбросить не может в принципе. Поэтому оба
# except были мёртвыми - они не сработали бы ни при каком вводе,
# и программа падала с traceback, хотя обработчики стоят в файле.
#
# СТАЛО: try внутри main(), вокруг кода, который реально выполняется
# и реально может сломаться.
#
# Правило: try ставится не вокруг того, что важно, а вокруг того,
# что может сломаться прямо сейчас, во время выполнения.
def main():
    try:
        print("Добро пожаловать в калькулятор!")
        a = float(input("Введите первое число: "))
        b = float(input("Введите второе число: "))
        operation = input("Введите операцию (сложение, вычитание, умножение, деление): ").strip().lower()

        if operation == "сложение":
            result = add(a, b)
        elif operation == "вычитание":
            result = subtract(a, b)
        elif operation == "умножение":
            result = multiply(a, b)
        elif operation == "деление":
            result = divide(a, b)
        else:
            result = "Неизвестная операция"

        print(f"Результат: {result}")

    except ZeroDivisionError:
        print("Не дели на 0")

    except ValueError:
        print('Введено не число')

    # Этот блок был закомментирован и лежал на верхнем уровне файла,
    # после class. Он и не мог работать отдельно: finally существует
    # только как часть try. Печатается всегда - и на успехе, и после
    # пойманной ошибки.
    finally:
        print("Операция завершена")


