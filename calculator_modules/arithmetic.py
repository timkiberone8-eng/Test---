
def add(x, y):
    """Возвращает сумму двух чисел"""
    return x + y


def subtract(x, y):
    """Возвращает разность двух чисел"""
    return x - y


def multiply(x, y):
    """Возвращает произведение двух чисел"""
    return x * y


def divide(x, y):
    """Возвращает частное двух чисел. Деление на ноль вызывает ошибку"""
    # БЫЛО:
    #     if y != 0:
    #         return x / y
    #     else:
    #         return "Ошибка: деление на ноль"
    #
    # При нуле функция возвращала СТРОКУ. Для программы это обычное
    # значение, такое же как число: никакой ошибки не происходит,
    # ZeroDivisionError не возникает, except для него не срабатывает,
    # и текст про ошибку спокойно печатается как результат вычисления.
    #
    # Заметь, что строка описания сверху обещала обратное: "Деление на
    # ноль вызывает ошибку". Не вызывало.
    #
    # СТАЛО: делим всегда, ошибку бросает сам Python, ловит её except
    # в main(). Ошибка должна быть ошибкой, а не текстом про ошибку.
    return x / y