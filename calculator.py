# А здесь калькулятор с урока 1, тот, до которого в прошлый раз не дошли.

# input() ВСЕГДА возвращает строку, даже если ввели цифры.
# float() превращает строку в число. Без него "2" + "3" дало бы "23",
# потому что для строк плюс означает склеить.
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))

# .strip() убирает пробелы по краям — легко случайно нажать пробел.
# .lower() опускает все буквы в нижний регистр, чтобы "Деление" и
# "ДЕЛЕНИЕ" тоже сработали.
#
# Если написать .upper() вместо .lower(), получится "ДЕЛЕНИЕ", а
# сравнивается оно с "деление" — совпадения не будет никогда, и
# программа промолчит. Именно это случилось у Тихона.
operation = input("Введите операцию (сложение, вычитание, умножение, деление): ").strip().lower()

if operation == "сложение":
    result = a + b
elif operation == "вычитание":
    result = a - b
elif operation == "умножение":
    result = a * b
elif operation == "деление":
    result = a / b
else:
    # Ветка else обязательна. Без неё при опечатке в слове программа
    # не напечатает ничего, и будет непонятно, сломалась она или нет.
    result = "Неизвестная операция"

# f-строка: то, что в фигурных скобках, подставляется в текст.
print(f"Результат: {result}")
